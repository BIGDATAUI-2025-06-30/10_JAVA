package Ch17;

/* ----------------------------------------------------------
   5. 클로저 기초 (Closure Basic)
   ----------------------------------------------------------
   설명 : 클로저 = "람다 + 그 람다가 캡처한 외부 변수" 한 묶음.
          람다가 만들어질 때 주변 지역변수의 값을 자기 안에 박제해서
          들고 다니는 구조.
   비유 : 람다 = 미니 객체. 만들어질 때 외부 값을 자기 주머니에 복사해 넣고
          나중에 호출되면 그 주머니에서 값을 꺼내 씀.
   포인트 : 1) 람다는 외부 변수 값을 자기 안에 "복사" 해서 가져간다
            2) 그래서 원본 지역변수는 바꿀 수 없다 (effectively final)
            3) 같은 람다 코드라도 만들 때 박제한 값이 다르면 결과가 다르다
   다음 단원 : C06ClosureMutable - 박스 메타포 + 값을 바꾸는 방법
   ---------------------------------------------------------- */

// 인사 - 이름을 박제해서 인사말을 돌려주는 가장 단순한 클로저용 인터페이스
interface Greeter {
	String say();
}

public class C05ClosureBasic {

	public static void main(String[] args) {

		// ====================================================
		// (1) 외부 변수 캡처 - 람다는 바깥 변수를 자기 안에 복사해 들고 간다
		// ====================================================
		String greeting = "안녕";   // effectively final
		Greeter g1 = () -> greeting + " 자바";
		System.out.println("(1) " + g1.say());

		// ====================================================
		// (2) effectively final - 캡처한 변수는 바깥에서도 못 바꾼다
		// ====================================================
		int number = 10;
		Greeter g2 = () -> "(2) 숫자 : " + number;
		// number = 20;   // ← 활성화하면 컴파일 에러
		System.out.println(g2.say());

		// ====================================================
		// (3) ★ 클로저 핵심 - "이름을 박제한 인사 람다 공장"
		//     ─────────────────────────────────────────────
		//     makeGreeter("철수") 호출 한 단계씩 :
		//       1) 매개변수 name 에 "철수" 들어감
		//       2) 람다 () -> "안녕 " + name 만들어짐
		//          ★ 이때 "철수" 가 람다 객체 안의 hidden field 로 복사됨
		//       3) 람다 반환 → makeGreeter 종료 → 매개변수 name 사라짐
		//       4) 그런데도 철수인사.say() 하면 "안녕 철수" 가 나옴
		//          ← 람다 안의 복사본이 살아있어서!
		// ====================================================
		Greeter 철수인사 = makeGreeter("철수");
		Greeter 영희인사 = makeGreeter("영희");

		System.out.println("(3) " + 철수인사.say());   // 안녕 철수
		System.out.println("(3) " + 영희인사.say());   // 안녕 영희

		// 같은 람다 코드인데 결과가 다른 이유 = 각자 다른 이름을 박제했기 때문
		System.out.println("(3) 철수인사 == 영희인사 ? "
				+ (철수인사 == 영희인사));    // false - 서로 다른 객체

		// ────────────────────────────────────────────────
		// 보너스 : 람다 안에서 박제된 값을 바꾸려 하면 컴파일 에러
		//
		//   static Greeter makeGreeter(String name) {
		//       return () -> {
		//           name = "변경시도";        // ← 컴파일 에러!
		//           return "안녕 " + name;
		//       };
		//   }
		//
		//   왜? 람다는 외부 변수 값을 복사해서 들고 다님.
		//       원본이 바뀌면 복사본과 어긋나 헷갈리니 자바가 아예 못 바꾸게 막음.
		//
		//   바꾸고 싶으면 → C06ClosureMutable 에서 배열 / 필드 트릭 사용
		// ────────────────────────────────────────────────
	}

	// 가장 단순한 클로저 공장 : name 박제해서 인사 람다 반환
	private static Greeter makeGreeter(String name) {
		// 람다가 만들어질 때 name 의 현재 값이 람다 객체 안에 복사됨
		return () -> "안녕 " + name;
	}
}
